// ── Rival AI · local studio-assistant engine ────────────────
// Deterministic, offline. Routes the request by keywords and
// answers as a design-studio assistant: briefs, budgets,
// services — and design itself.

type Topic =
  | 'tz'
  | 'service'
  | 'budget'
  | 'deadline'
  | 'edits'
  | 'process'
  | 'palette'
  | 'typography'
  | 'logo'
  | 'composition'
  | 'critique'
  | 'idea'

function detectTopic(text: string): Topic {
  const t = text.toLowerCase()
  const has = (...words: string[]) => words.some((w) => t.includes(w))

  if (has('тз', 'техническое задание', 'бриф', 'составь задание', 'задание для')) return 'tz'
  if (has('какую услугу', 'что заказать', 'услуг', 'нужен аватар', 'нужен логотип', 'нужен баннер')) return 'service'
  if (has('цен', 'стоимост', 'бюджет', 'сколько стоит', 'прайс', 'деньг')) return 'budget'
  if (has('срок', 'когда будет', 'быстро', 'срочн', 'к дедлайну')) return 'deadline'
  if (has('правк', 'переделат', 'не понравил', 'изменит')) return 'edits'
  if (has('как работае', 'этап', 'процесс', 'что дальше', 'как заказат')) return 'process'
  if (has('палитр', 'цвет', 'градиент', 'контраст')) return 'palette'
  if (has('шрифт', 'типограф', 'кернинг', 'леттеринг')) return 'typography'
  if (has('логотип', 'знак', 'фирстиль', 'айдентик', 'бренд')) return 'logo'
  if (has('композиц', 'макет', 'сетк', 'отступ', 'иерарх')) return 'composition'
  if (has('критик', 'оцени', 'посмотри', 'разбер', 'что не так', 'улучшить')) return 'critique'
  return 'idea'
}

const withContext = (context?: string, fallback = '') =>
  context ? `\nПрименимо к «${context}» напрямую.` : fallback

export function generateReply(userText: string, context?: string): string {
  const topic = detectTopic(userText)
  const firstLine = userText.trim().split('\n')[0].slice(0, 80)

  switch (topic) {
    case 'tz':
      return (
        `Черновик ТЗ по твоей задаче:\n\n` +
        `Проект: ${firstLine}\n` +
        `Задача: что результат должен сделать для бизнеса (узнать, кликнуть, запомнить)\n` +
        `Аудитория: кто увидит первым и в каком контексте\n` +
        `Формат: размер площадки, где будет жить\n` +
        `Настроение: 3 прилагательных вместо «стильно и дорого»\n` +
        `Референсы: 2–3 примера «в эту сторону» и один «не сюда»\n\n` +
        `Ответь на пункты по порядку — соберу финальное ТЗ, и можно оформлять заказ.` +
        withContext(context)
      )

    case 'service':
      return (
        `Ориентир по услугам:\n` +
        `• нужен лицо канала или стрима — Аватар\n` +
        `• обложка канала, реклама — Баннер\n` +
        `• цепляющая картинка видео — Превью\n` +
        `• имя и знак под бизнес — Логотип\n` +
        `• система: знак, палитра, носители — Айдентика\n` +
        `• арт для релиза музыки — Обложка\n` +
        `Скажи задачу своими словами — назову услугу и срок.` +
        withContext(context)
      )

    case 'budget':
      return (
        `Цены студии — «от», финал зависит от объёма:\n` +
        `• Превью от 1 500 ₽, Баннер от 1 800 ₽, Аватар от 2 500 ₽\n` +
        `• Обложка релиза от 3 500 ₽, Логотип от 6 000 ₽, Айдентика от 15 000 ₽\n` +
        `Что поднимает цену: дополнительные форматы, срочность, поиск уникальной идеи.\n` +
        `Назови задачу — скажу вилку честно, без вилки «от 990».` +
        withContext(context)
      )

    case 'deadline':
      return (
        `Сроки по услугам:\n` +
        `• Превью и Баннер — 1 день\n` +
        `• Аватар — 1–2 дня, Обложка — 2–3 дня\n` +
        `• Логотип — 3–5 дней, Айдентика — 1–2 недели\n` +
        `Срочно — возможно, но +50% к цене и только на простых задачах. Дедлайн «вчера» ломает качество раньше, чем график.` +
        withContext(context)
      )

    case 'edits':
      return (
        `Правки в студии:\n` +
        `• в смету входят два круга правок по выбранному варианту\n` +
        `• правки = «сделать ближе к цели», а не «а покажите ещё 5 других»\n` +
        `• новый курс после согласования — отдельный мини-заказ\n` +
        `Поэтому на старте так важно ТЗ: оно защищает и тебя, и студию.` +
        withContext(context)
      )

    case 'process':
      return (
        `Как идёт заказ:\n` +
        `1. Заявка: услуга, бриф, бюджет, срок\n` +
        `2. Ответ студии в течение ~2 часов, уточнения\n` +
        `3. Работа: концепция, затем чистовик\n` +
        `4. Согласование: два круга правок\n` +
        `5. Готово: файлы во всех нужных форматах\n` +
        `Статус всегда видно в разделе «Профиль».` +
        withContext(context)
      )

    case 'palette':
      return (
        `Рабочая схема для тёмного интерфейса:\n` +
        `• база: почти чёрный с лёгкой синевой (#0A0D16)\n` +
        `• поверхность на 8–12% светлее базы\n` +
        `• один акцент (индиго или лаванда) только для действия\n` +
        `Правило: акцент занимает меньше 10% экрана, тогда он работает.` +
        withContext(context)
      )

    case 'typography':
      return (
        `Коротко о паре шрифтов:\n` +
        `• заголовки: геометрический гротеск (Space Grotesk, Clash Display)\n` +
        `• текст: нейтральный (Inter, Suisse)\n` +
        `Контраст создавай размером и весом, а не капсом: 28/600 против 14/400 читается лучше, чем ВСЁ КАПСОМ.\n` +
        `Интерлиньяж текста 1.5–1.6, у заголовков 1.1–1.2.` +
        withContext(context)
      )

    case 'logo':
      return (
        `Знак начинай с чёрно-белого эскиза: если не работает без цвета, не заработает и с ним.\n` +
        `Три проверки перед показом заказчику:\n` +
        `• читается ли в 24px\n` +
        `• выживает ли в монохроме\n` +
        `• отличим ли от двух главных конкурентов ниши\n` +
        `Геометрию строй от модуля, а не на глаз: сетка даёт ту самую «дорогую» точность.` +
        withContext(context)
      )

    case 'composition':
      return (
        `Иерархия решает до того, как вступает красота:\n` +
        `• один главный элемент на экран, остальное приглушай\n` +
        `• интервалы группируй кратными шагами (4 / 8 / 12 / 24): ритм считывается подсознательно\n` +
        `• прижми связанное, раздвинь несвязанное: расстояние тоже язык\n` +
        `Проверка: прищурься. Должен выжить один силуэт композиции.` +
        withContext(context)
      )

    case 'critique':
      return (
        `Разбираю по трём слоям:\n` +
        `1. Смысл: понятно ли за секунду, что это и для кого\n` +
        `2. Иерархия: ведёт ли взгляд от главного к деталям без ступоров\n` +
        `3. Отделка: ритм отступов, вес шрифтов, точность выравнивания\n` +
        `Чаще всего ломается второй слой: элементов много, а ведущего нет. Убери всё, что не помогает первому действию, и макет оживает.` +
        withContext(context, '\nПришли детали или скрин, разберу предметнее.')
      )

    // idea + default
    default:
      return (
        `Разожму задачу тремя вопросами, отвечай по порядку:\n` +
        `1. Кто увидит результат первым и что он должен почувствовать?\n` +
        `2. Что здесь можно убрать без потери смысла?\n` +
        `3. Какое одно решение сделает работу узнаваемой среди сотни похожих?\n` +
        `Ответь на первый, предложу три направления развития.` +
        withContext(context, '')
      )
  }
}

